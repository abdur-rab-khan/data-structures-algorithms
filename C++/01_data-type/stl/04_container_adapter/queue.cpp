/*
+------------------------------------------------------------------------------------------------------------------------------------------------------------------+
|                                                                              💻 QUEUE                                                                            |
+------------------------------------------------------------------------------------------------------------------------------------------------------------------+
|                                                                                                                                                                  |
| 🟡 Queue is a data structure that follow "FIFO" model Where we push element from "back" and pop from "front".                                                    |
|                                                                                                                                                                  |
+------------------------------------------------------------------------------------------------------------------------------------------------------------------+
|                                                                          🔶 QUEUE METHODS                                                                        |
+------------------------------------------------------------------------------------------------------------------------------------------------------------------+
|                                                                                                                                                                  |
| 1. "q.push(x)": Add element "x" at back.                                                                                                                         |
|                                                                                                                                                                  |
| 2. "q.pop()": Remove element from "front".                                                                                                                       |
|                                                                                                                                                                  |
| 3. "q.front()": Return the first element.                                                                                                                        |
|                                                                                                                                                                  |
| 4. "q.back()": Return the last element.                                                                                                                          |
|                                                                                                                                                                  |
| 5. "q.empty()": Return true if queue is empty.                                                                                                                   |
|                                                                                                                                                                  |
| 6. "q.size()": Return the size of the queue.                                                                                                                     |
|                                                                                                                                                                  |
+------------------------------------------------------------------------------------------------------------------------------------------------------------------+
*/

#include <bits/stdc++.h>
using namespace std;

int main() {
    queue<int> q;

    q.push(1);
    q.push(2);
    q.push(3);

    cout << "Front element is: " << q.front();  // 1
    cout << "Front element is: " << q.back();   // 3

    q.pop();
    q.pop();
    q.pop();
    q.pop();

    return 0;
}
