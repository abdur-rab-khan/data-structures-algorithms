#include <bits/stdc++.h>
using namespace std;

namespace permutation_combination {
    // Finding factorial using iteration 
    void factorialIt(int a){
        int ans = 1;

        for (int i = a; i > 1; i--){
            ans *= i;
        }

        cout << "Factorial of " << a << " is " << ans << endl;
    }

    void main(){
        factorialIt(5);
    }
}

int main() {
    permutation_combination::main();

    return 0;
}